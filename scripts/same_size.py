#!/usr/bin/env python
"""Same-size comparison on the text benchmark: ~4B Qwen-family systems against TypeSafe's decision models, from saved
replies only. EXPLORATORY: framed after the results were seen.

    python scripts/same_size.py           # configs/analysis/part2_same_size.yaml -> results/ and figures/part2_same_size/
    python scripts/same_size.py --check   # exit 1 if the tables differ from a fresh rebuild (figures aren't compared)

Free: reads results/, results/run_ids.yaml, configs/prices.yaml and the config. No model calls, no data/. Stops with
an error if a configured run or model is missing. Logic: src/asimov/same_size.py. Choices: WORKLOG 2026-10-14,
"Same-size comparison: Qwen family vs decision models (exploratory)". Numbers and figures only, no interpretation.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import matplotlib
import yaml

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.text import Text  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from asimov.bench.text import parse_decision_prompt  # noqa: E402
from asimov.bench.text_score import QUESTIONS  # noqa: E402
from asimov.cascade import MEAN, Accuracy  # noqa: E402
from asimov.collect.load import ModelResult, RunData, load_results  # noqa: E402
from asimov.collect.tables import to_csv  # noqa: E402
from asimov.prices import PRICES_PATH, PriceTable, load_prices  # noqa: E402
from asimov.run_ids import read_ids  # noqa: E402
from asimov.same_size import (  # noqa: E402
    MATCHED_QUESTIONS,
    ContrastResult,
    RowResult,
    RowSpec,
    SameSizeConfig,
    contrast_family,
    row_result,
)

CONFIG_PATH = ROOT / "configs" / "analysis" / "part2_same_size.yaml"
GENERATED = "<!-- Generated by scripts/same_size.py from results/. Don't edit by hand: rerun it. -->"
LABEL = {MEAN: "Mean of 4", **{q: f"Q{k} {q}" for k, q in enumerate(QUESTIONS, 1)}}
SHORT = {MEAN: "mean of 4", **{q: f"Q{k}" for k, q in enumerate(QUESTIONS, 1)}}
SELF_HOSTED = "self-hosted, GPU time"
ALPHA = 0.05  # Holm-adjusted p below this is marked in the contrasts table
DIGITS = 3
FIG_FORMATS = ("png", "pdf")
FIG_SIZE = (9, 6)
FIG_DPI = 150
LABEL_STEPS = (0, 9, -9, 18, -18, 27, -27, 36, -36)  # points up or down from the marker
LABEL_OFFSETS = [(dx, dy) for dx in (6, -6) for dy in LABEL_STEPS]  # right of the marker first, then left
GROUP_COLORS = ("#1f77b4", "#ff7f0e", "#2ca02c", "#d62728", "#9467bd", "#8c564b", "#e377c2")


def find(runs: list[RunData], spec: RowSpec) -> tuple[RunData, ModelResult]:
    run = next((r for r in runs if r.name == spec.run), None)
    if run is None:
        raise ValueError(f"row {spec.label!r}: no run named {spec.run!r} under results/; is it merged into this branch?")
    model = next((m for m in run.models if m.summary["model"] == spec.model), None)
    if model is None:
        raise ValueError(f"row {spec.label!r}: run {spec.run!r} has no model {spec.model!r}")
    return run, model


def is_cumulative(prompt: str) -> bool:
    return prompt.startswith("decision_") and parse_decision_prompt(prompt).mode == "cumulative"


def rows(cfg: SameSizeConfig, runs: list[RunData], prices: PriceTable) -> list[RowResult]:
    out = []
    for spec in cfg.rows:
        _, model = find(runs, spec)
        if spec.model not in prices.models:
            raise ValueError(f"row {spec.label!r}: {spec.model!r} has no entry in configs/prices.yaml")
        out.append(row_result(spec, model, prices.models[spec.model], is_cumulative(model.summary["prompt"])))
    return out


def fmt(a: Accuracy, signed: bool = False) -> str:
    f = f"+.{DIGITS}f" if signed else f".{DIGITS}f"
    return f"{a.value:{f}} [{a.lo:{f}}, {a.hi:{f}}]"


def params(r: RowResult) -> str:
    if r.params_b is None:
        return "not published"
    return f"{r.params_b:g}B" + (f", {r.active_params_b:g}B active" if r.active_params_b else "")


def cost(r: RowResult) -> str:
    return SELF_HOSTED if r.cost_per_1000 is None else f"${r.cost_per_1000:.3f}"


def pval(p: float | None) -> str:
    return "–" if p is None else f"{p:.2g}" if p < 0.001 else f"{p:.3f}"


def row(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def table(head: list[str], body: list[list[str]]) -> list[str]:
    return [row(head), row(["---"] * len(head)), *(row(b) for b in body), ""]


def system_cell(r: RowResult, ids: dict[str, str]) -> str:
    flag = f" **Flag: {r.spec.flag}**" if r.spec.flag else ""
    return f"{r.spec.label} ({ids.get(r.spec.run, '?')}){flag}"


def rows_section(results: list[RowResult], ids: dict[str, str]) -> list[str]:
    head = ["Group", "System (run)", "n", *(LABEL[m] for m in (*QUESTIONS, MEAN)), "Unreadable", "Latency p50 (s)"]
    head += ["Latency source", "Parameters", "$ per 1,000 items"]
    body = [
        [r.spec.group, system_cell(r, ids), str(r.n), *(fmt(r.accuracy[m]) for m in (*QUESTIONS, MEAN))]
        + [f"{r.unreadable_rate:.1%}", f"{r.latency_p50:.3f}", r.latency_source, params(r), cost(r)]
        for r in results
    ]
    return ["## Rows", "", *table(head, body)]


def matched_section(results: list[RowResult]) -> list[str]:
    head = ["System", "n Q1 matched", *(f"{SHORT[q]} on Q1-matched items" for q in MATCHED_QUESTIONS)]
    body = [
        [
            r.spec.label,
            str(r.n_q1_matched),
            *("–" if r.q1_matched[q] is None else f"{r.q1_matched[q]:.3f}" for q in MATCHED_QUESTIONS),
        ]
        for r in results
    ]
    note = "From summary.json. Each row's subset differs (its own Q1 hits), so compare rows on the strict table above."
    return ["## Q2-Q4 on the items whose Q1 matched the key", "", note, "", *table(head, body)]


def contrasts_section(contrasts: list[ContrastResult]) -> list[str]:
    lines = ["## Paired contrasts", ""]
    lines += [
        "Difference = first row minus second, on the same items. Per question: paired bootstrap 95% CI, exact McNemar "
        f"(discordant items: first only / second only), Holm across all {sum(len(c.tests) - 1 for c in contrasts)} question "
        f"tests; **bold** = Holm p < {ALPHA}. Mean of 4: paired bootstrap CI only.",
        "",
    ]
    for k, c in enumerate(contrasts, 1):
        lines += [f"### ({k}) {c.spec.a} vs {c.spec.b} ({c.spec.kind})", "", f"Changes: {c.spec.changes}. n = {c.n}.", ""]
        body = []
        for t in c.tests:
            holm_cell = pval(t.p_holm)
            if t.p_holm is not None and t.p_holm < ALPHA:
                holm_cell = f"**{holm_cell}**"
            discordant = "–" if t.a_only is None else f"{t.a_only} / {t.b_only}"
            body.append([LABEL[t.metric], fmt(t.diff, signed=True), discordant, pval(t.p), holm_cell])
        lines += table(["Metric", "Difference [95% CI]", "Discordant", "McNemar p", "Holm p"], body)
    return lines


def tables_md(cfg: SameSizeConfig, cfg_path: Path, results: list[RowResult], contrasts, ids, prices: PriceTable) -> str:
    lines = [
        GENERATED,
        "",
        "# Same-size comparison: Qwen family vs decision models (text benchmark)",
        "",
        f"**{cfg.label}**",
        "",
        f'From saved replies only (`{cfg_path.name}`); choices in WORKLOG 2026-10-14, "Same-size comparison". Numbers only.',
        "",
        "- Accuracy: exact answer per question; unanswered = wrong. 95% CIs: Wilson per question, bootstrap over items for "
        "the mean of 4 (each item's share of its 4 questions right).",
        "- Unreadable: summary `parse_failure_rate` (items with at least one answer that couldn't be read).",
        "- Latency p50: median over items. `Modal compute_s` = GPU time on Modal without queueing (`raw.remote.compute_s`); "
        "`round trip` = the recorded `latency_s`; for cumulative runs, the 4 sequential calls together.",
        f"- $: logged tokens x `configs/prices.yaml` (checked {prices.checked.isoformat()}); `{SELF_HOSTED}` = no token price.",
        "",
        *rows_section(results, ids),
        *matched_section(results),
        *contrasts_section(contrasts),
    ]
    return "\n".join(lines).rstrip() + "\n"


def acc_columns(acc: dict[str, Accuracy], prefix: str = "") -> dict:
    return {f"{prefix}{m}_{k}": getattr(a, k) for m, a in acc.items() for k in ("value", "lo", "hi")}


def csv_files(cfg: SameSizeConfig, results: list[RowResult], contrasts: list[ContrastResult], ids) -> dict[str, str]:
    banner = f"# {cfg.label}\n"
    row_dicts = [
        {
            "label": r.spec.label,
            "group": r.spec.group,
            "run": r.spec.run,
            "run_id": ids.get(r.spec.run),
            "model": r.spec.model,
            "flag": r.spec.flag,
            "n": r.n,
            **acc_columns(r.accuracy),
            "n_q1_matched": r.n_q1_matched,
            **{f"{q}_accuracy_q1_matched": r.q1_matched[q] for q in MATCHED_QUESTIONS},
            "unreadable_rate": r.unreadable_rate,
            "latency_p50_s": r.latency_p50,
            "latency_source": r.latency_source,
            "params_b": r.params_b,
            "active_params_b": r.active_params_b,
            "cost_per_1000_usd": r.cost_per_1000,
        }
        for r in results
    ]
    contrast_dicts = [
        {
            "contrast": k,
            "a": c.spec.a,
            "b": c.spec.b,
            "kind": c.spec.kind,
            "metric": t.metric,
            "n": c.n,
            "diff": t.diff.value,
            "diff_lo": t.diff.lo,
            "diff_hi": t.diff.hi,
            "a_only": t.a_only,
            "b_only": t.b_only,
            "mcnemar_p": t.p,
            "holm_p": t.p_holm,
        }
        for k, c in enumerate(contrasts, 1)
        for t in c.tests
    ]
    lead = ("contrast", "a", "b", "kind", "metric", "n", "diff", "diff_lo", "diff_hi", "a_only", "b_only")
    return {
        "rows.csv": banner + to_csv(row_dicts, ("label", "group", "run", "run_id", "model", "flag", "n")),
        "contrasts.csv": banner + to_csv(contrast_dicts, (*lead, "mcnemar_p", "holm_p")),
    }


def place_labels(fig, ax, points: list[tuple[str, float, float]]) -> None:
    """Label each point, moving a label up or down (then to the left) until it overlaps no earlier label and stays inside
    the axes; a moved label gets a thin line to its point."""
    renderer = fig.canvas.get_renderer()  # pyright: ignore[reportAttributeAccessIssue]
    inside = ax.get_window_extent(renderer)
    placed = []
    for text, x, y in sorted(points, key=lambda p: -p[2]):
        candidates = [*LABEL_OFFSETS, LABEL_OFFSETS[0]]  # nothing fits: the first choice
        for k, (dx, dy) in enumerate(candidates):
            ha = "left" if dx > 0 else "right"
            line = {"arrowstyle": "-", "lw": 0.5, "color": "0.4"} if dy else None
            kw = {"textcoords": "offset points", "xytext": (dx, dy), "fontsize": 7, "ha": ha, "va": "center"}
            note = ax.annotate(text, (x, y), arrowprops=line, **kw)
            note.update_positions(renderer)
            box = Text.get_window_extent(note, renderer)  # the text alone: an annotation's own extent includes its line
            fits = box.x0 >= inside.x0 and box.x1 <= inside.x1 and not any(box.overlaps(b) for b in placed)
            if fits or k == len(candidates) - 1:
                break
            note.remove()
        placed.append(box)


def scatter(results: list[RowResult], x_of, xlabel: str, log_x: bool, banner: str, path: Path) -> None:
    """Mean of 4 (bootstrap 95% CI) against one x per row, coloured by group."""
    groups = list(dict.fromkeys(r.spec.group for r in results))
    fig, ax = plt.subplots(figsize=FIG_SIZE)
    for r in results:
        acc = r.accuracy[MEAN]
        c = GROUP_COLORS[groups.index(r.spec.group) % len(GROUP_COLORS)]
        yerr = [[max(0.0, acc.value - acc.lo)], [max(0.0, acc.hi - acc.value)]]
        ax.errorbar(x_of(r), acc.value, yerr=yerr, fmt="o", color=c, ms=6, capsize=3)
    for g in groups:
        ax.plot([], [], "o", color=GROUP_COLORS[groups.index(g) % len(GROUP_COLORS)], label=g)
    if log_x:
        ax.set_xscale("log")
    ax.set_xlabel(xlabel)
    ax.set_ylabel("accuracy, mean of 4 (95% bootstrap CI)")
    ax.grid(alpha=0.3, which="both")
    ax.legend(fontsize=8, loc="lower right")
    ax.set_title(banner, fontsize=9)
    fig.tight_layout()  # before the labels: placing them reads their final position on the canvas
    place_labels(fig, ax, [(r.spec.label, x_of(r), r.accuracy[MEAN].value) for r in results])
    path.parent.mkdir(parents=True, exist_ok=True)
    for ext in FIG_FORMATS:
        meta = {"CreationDate": None} if ext == "pdf" else None
        fig.savefig(path.with_name(f"{path.name}.{ext}"), dpi=FIG_DPI, metadata=meta)
    plt.close(fig)


def draw(results: list[RowResult], banner: str, out: Path) -> None:
    lat = "latency p50 per item, s (log; Modal compute_s where saved, else round trip)"
    scatter(results, lambda r: r.latency_p50, lat, True, banner, out / "accuracy_vs_latency")
    unread = "unreadable (parse-failure) rate"
    scatter(results, lambda r: r.unreadable_rate, unread, False, banner, out / "accuracy_vs_unreadable")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", type=Path, default=CONFIG_PATH)
    ap.add_argument("--results", type=Path, default=ROOT / "results")
    ap.add_argument("--figures", type=Path, default=ROOT / "figures")
    ap.add_argument("--prices", type=Path, default=PRICES_PATH)
    ap.add_argument("--check", action="store_true", help="compare the tables with a fresh rebuild instead of writing")
    args = ap.parse_args(argv)

    cfg = SameSizeConfig.model_validate(yaml.safe_load(args.config.read_text()))
    prices = load_prices(args.prices)
    ids = read_ids(args.results)
    results = rows(cfg, load_results(args.results), prices)
    contrasts = contrast_family(cfg.contrasts, {r.spec.label: r.system for r in results})
    files = csv_files(cfg, results, contrasts, ids)
    files["tables.md"] = tables_md(cfg, args.config, results, contrasts, ids, prices)
    out = args.results / args.config.stem
    if args.check:
        stale = [name for name, text in files.items() if not (out / name).exists() or (out / name).read_text() != text]
        for name in stale:
            print(f"stale: {out / name}")
        return 1 if stale else 0
    out.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (out / name).write_text(text)
    draw(results, cfg.label, args.figures / args.config.stem)
    print(f"wrote {len(files)} tables to {out} and 2 figures to {args.figures / args.config.stem}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
