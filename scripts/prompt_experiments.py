#!/usr/bin/env python
"""Part 2 prompt experiments (EXPLORATORY) on the text benchmark, from saved replies only.

    python scripts/prompt_experiments.py           # configs/analysis/prompt_experiments.yaml -> results/prompt_experiments/
    python scripts/prompt_experiments.py --check   # exit 1 if the tables differ from a fresh rebuild

Free: reads results/ and configs/prices.yaml. No model calls, no data/. Each LLM with a hint prompt variant is compared
with the same LLM alone (repro_fig4) on the same items. Logic: src/asimov/prompt_experiments.py. Choices: WORKLOG
2026-10-14, "Part 2 prompt experiments (exploratory, paid)". Numbers only, no interpretation.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from asimov.cascade import Accuracy  # noqa: E402
from asimov.collect.load import RunData, load_results  # noqa: E402
from asimov.collect.tables import to_csv  # noqa: E402
from asimov.prices import PRICES_PATH, PriceTable, load_prices  # noqa: E402
from asimov.prompt_experiments import Comparison, ExperimentConfig, Result, compare  # noqa: E402
from cascade import LABEL, fmt, money, row, seconds, system  # noqa: E402  (scripts/cascade.py)

CONFIG_PATH = ROOT / "configs" / "analysis" / "prompt_experiments.yaml"
GENERATED = "<!-- Generated by scripts/prompt_experiments.py from results/. Don't edit by hand: rerun it. -->"
DIGITS = 3
TITLE = {
    "hints": "{llm} given Jev's 4 picks as hints (`{run}`) vs {llm} alone",
    "q2_q4": "Q1 from Jev, Q2-Q4 from {llm} told Jev's injury (`{run}`) vs {llm} alone",
}
SYSTEM = {"hints": "{llm} + Jev hints", "q2_q4": "Jev Q1 + {llm} Q2-Q4"}


def signed(a: Accuracy) -> str:
    return f"{a.value:+.{DIGITS}f} [{a.lo:+.{DIGITS}f}, {a.hi:+.{DIGITS}f}]"


def section(c: Comparison, r: Result, llm: str, first: str) -> list[str]:
    name = SYSTEM[c.kind].format(llm=llm)
    lines = [f"## {TITLE[c.kind].format(llm=llm, run=c.variant.run)}", "", f"n = {r.n} items.", ""]
    lines += [
        row(
            [
                "",
                f"{llm} alone",
                name,
                "Difference (paired bootstrap)",
                "McNemar p (alone-only / system-only right)",
                f"{first} alone",
            ]
        )
    ]
    lines += [row(["---"] * 6)]
    for m in r.rows:
        mc = "–" if m.mcnemar_p is None else f"{m.mcnemar_p:.3g} ({m.baseline_only} / {m.system_only})"
        lines.append(row([LABEL[m.metric], fmt(m.baseline), fmt(m.system), signed(m.diff), mc, fmt(r.first[m.metric])]))
    lines.append(
        row(
            [
                "$ per 1,000 items",
                money(r.baseline_cost_per_1000),
                money(r.system_cost_per_1000),
                "",
                "",
                money(r.first_cost_per_1000),
            ]
        )
    )
    lines.append(row(["Latency p50 (s)", seconds(r.baseline_p50), seconds(r.system_p50), "", "", seconds(r.first_p50)]))
    return [*lines, ""]


def tables_md(
    results: list[tuple[Comparison, Result, str]], cfg: ExperimentConfig, cfg_path: Path, prices: PriceTable, first: str
) -> str:
    lines = [
        GENERATED,
        "",
        "# Part 2 prompt experiments (text benchmark)",
        "",
        f"**{cfg.label}**",
        "",
        f'From saved replies only (`{cfg_path.name}`); WORKLOG 2026-10-14, "Part 2 prompt experiments". Numbers only.',
        "",
        "- Accuracy: the exact answer per question (Q2 and Q4: exact severity level, as in Fig 4); mean of 4 = each item's "
        "share of its 4 questions right, averaged over items. 95% CIs: Wilson per question, bootstrap over items for the "
        "mean of 4. Difference = system minus the LLM alone, paired percentile bootstrap over items. McNemar: exact, "
        "two-sided, per question, no multiple-comparison correction. An unanswered question is wrong.",
        f"- $: logged tokens x `configs/prices.yaml` (checked {prices.checked.isoformat()}), per 1,000 items. Every system "
        f"with {first}'s picks includes {first}'s call, and its latency is added to the LLM's (sequential calls). "
        "Latency p50 = median over items; the four variant runs ran at the same time (8 workers each), the "
        "baseline runs did not, so latency is not like for like.",
        f"- Q1 of the `q2_q4` system is {first}'s saved answer; that run's own summary scores Q1 as unanswered by design.",
        "",
    ]
    for c, r, llm in results:
        lines += section(c, r, llm, first)
    return "\n".join(lines).rstrip() + "\n"


def csv_rows(results: list[tuple[Comparison, Result, str]]) -> str:
    rows = []
    for c, r, _ in results:
        for m in r.rows:
            rows.append(
                {
                    "kind": c.kind,
                    "variant_run": c.variant.run,
                    "baseline_run": c.baseline.run,
                    "model": c.variant.model,
                    "metric": m.metric,
                    "n": r.n,
                    **{
                        f"{who}_{k}": getattr(a, k)
                        for who, a in (("baseline", m.baseline), ("system", m.system), ("diff", m.diff))
                        for k in ("value", "lo", "hi")
                    },
                    "first_alone": r.first[m.metric].value,
                    "mcnemar_p": m.mcnemar_p,
                    "baseline_only_right": m.baseline_only,
                    "system_only_right": m.system_only,
                    "baseline_cost_per_1000_usd": r.baseline_cost_per_1000,
                    "system_cost_per_1000_usd": r.system_cost_per_1000,
                    "first_cost_per_1000_usd": r.first_cost_per_1000,
                    "baseline_latency_p50_s": r.baseline_p50,
                    "system_latency_p50_s": r.system_p50,
                    "first_latency_p50_s": r.first_p50,
                }
            )
    return to_csv(rows, ("kind", "variant_run", "baseline_run", "model", "metric"))


def analyse(cfg: ExperimentConfig, runs: list[RunData], prices: PriceTable) -> tuple[list[tuple[Comparison, Result, str]], str]:
    first = system(runs, cfg.first, prices, None)
    out = []
    for c in cfg.comparisons:
        baseline, variant = system(runs, c.baseline, prices, None), system(runs, c.variant, prices, None)
        out.append((c, compare(c.kind, first, baseline, variant), baseline.name))
    return out, first.name


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", type=Path, default=CONFIG_PATH)
    ap.add_argument("--results", type=Path, default=ROOT / "results")
    ap.add_argument("--prices", type=Path, default=PRICES_PATH)
    ap.add_argument("--check", action="store_true", help="compare the tables with a fresh rebuild instead of writing")
    args = ap.parse_args(argv)

    cfg = ExperimentConfig.model_validate(yaml.safe_load(args.config.read_text()))
    prices = load_prices(args.prices)
    results, first = analyse(cfg, load_results(args.results), prices)
    files = {"comparisons.csv": csv_rows(results), "tables.md": tables_md(results, cfg, args.config, prices, first)}
    out = args.results / args.config.stem
    if args.check:
        stale = [name for name, text in files.items() if not (out / name).exists() or (out / name).read_text() != text]
        for name in stale:
            print(f"stale: {out / name}")
        return 1 if stale else 0
    out.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (out / name).write_text(text)
    print(f"wrote {len(files)} tables to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
