#!/usr/bin/env python
"""Part 2 designs D (route by confidence) and B (split by question) on the text benchmark, from saved replies only.

    python scripts/cascade.py           # configs/analysis/part2_designs.yaml -> results/part2_designs/, figures/part2_designs/
    python scripts/cascade.py --check   # exit 1 if the tables differ from a fresh rebuild (figures aren't compared)

Free: reads results/, configs/prices.yaml, configs/paper/claims.yaml (majority baselines) and the design config. No
model calls, no data/. Every decision model in `first` is paired with every LLM in `escalation`; new runs are picked
up by adding a config line. Logic: src/asimov/cascade.py. Choices: WORKLOG 2026-10-13, "Part 2 design analysis".
Numbers and figures only, no interpretation.
"""

from __future__ import annotations

import argparse
import sys
import textwrap
from dataclasses import dataclass
from pathlib import Path

import matplotlib
import yaml

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from asimov.bench.text_score import QUESTIONS  # noqa: E402
from asimov.cascade import (  # noqa: E402
    MEAN,
    METRICS,
    Accuracy,
    DesignConfig,
    Point,
    RunModel,
    SplitRow,
    System,
    at_fraction,
    cascade_curve,
    perfect_router,
    split_table,
    summarise,
    system_from,
)
from asimov.claims import CLAIMS_PATH, Claims, load_claims  # noqa: E402
from asimov.collect.load import ModelResult, RunData, load_results  # noqa: E402
from asimov.collect.tables import to_csv  # noqa: E402
from asimov.plot_data import baseline, color  # noqa: E402
from asimov.prices import PRICES_PATH, PriceTable, load_prices  # noqa: E402

CONFIG_PATH = ROOT / "configs" / "analysis" / "part2_designs.yaml"
GENERATED = "<!-- Generated by scripts/cascade.py from results/. Don't edit by hand: rerun it. -->"
SMOKE = "**n = {n}, fewer than the LLM run's {full}: smoke run, not a result.**"
LABEL = {MEAN: "Mean of 4", **{q: f"Q{k} {q}" for k, q in enumerate(QUESTIONS, 1)}}
SHORT = {MEAN: "mean of 4", **{q: f"Q{k}" for k, q in enumerate(QUESTIONS, 1)}}
DIGITS = 3
FIG_FORMATS = ("png", "pdf")
NOTE_WIDTH = 48  # characters per line of the note under the legend


@dataclass(frozen=True)
class Pair:
    first: System
    escalate: System
    first_ref: RunModel
    escalate_ref: RunModel
    first_note: str  # how the decision model's own calls are priced
    full_n: int  # items the LLM run has: fewer in `first` marks a smoke run


@dataclass(frozen=True)
class Analysis:
    pair: Pair
    curve: list[Point]
    frontiers: dict[str, list[Point]]  # metric -> perfect router
    fixed: dict[float, Point]
    llm_alone: Point
    splits: list[SplitRow]


def find(runs: list[RunData], ref: RunModel) -> ModelResult:
    run = next((r for r in runs if r.name == ref.run), None)
    if run is None:
        raise ValueError(f"no run named {ref.run!r} under results/")
    model = next((m for m in run.models if m.summary["model"] == ref.model), None)
    if model is None:
        raise ValueError(f"run {ref.run!r} has no model {ref.model!r}")
    return model


def price_note(prices: PriceTable, model: str) -> str:
    p = prices.models[model]
    size = f"{p.params_b:g}B parameters" + (f", {p.active_params_b:g}B active" if p.active_params_b else "") if p.params_b else ""
    if p.self_hosted:
        return f"self-hosted ({p.self_hosted}): its GPU time is not in $" + (f"; {size}" if size else "")
    if p.free_tier:
        return "free tier: its calls cost $0" + (f"; {size}" if size else "")
    return "priced per token"


def system(runs: list[RunData], ref: RunModel, prices: PriceTable, rule: str | None) -> System:
    if ref.model not in prices.models:
        raise ValueError(f"{ref.model!r} has no entry in configs/prices.yaml")
    return system_from(find(runs, ref), prices.models[ref.model], rule)


def analyse(pair: Pair, cfg: DesignConfig) -> Analysis:
    first, llm = pair.first, pair.escalate
    alone = [llm.items[i] for i in sorted(first.items)]
    return Analysis(
        pair,
        cascade_curve(first, llm),
        {m: perfect_router(first, llm, m) for m in METRICS},
        {f: at_fraction(first, llm, f) for f in cfg.fixed_fractions},
        Point(None, len(alone), len(alone), *summarise(alone, METRICS)),
        split_table(first, llm, cfg.split_headline),
    )


def acc_columns(acc: dict[str, Accuracy]) -> dict:
    return {f"{m}_{k}": getattr(a, k) for m, a in acc.items() for k in ("value", "lo", "hi")}


def point_row(a: Analysis, p: Point, **extra) -> dict:
    return {
        "first": a.pair.first_ref.model,
        "escalation": a.pair.escalate_ref.model,
        **extra,
        "n": p.n,
        "n_sent": p.n_sent,
        "share_sent": p.n_sent / p.n,
        "cost_per_1000_usd": p.cost_per_1000,
        "latency_p50_s": p.latency_p50,
        **acc_columns(p.accuracy),
    }


def best_at(frontier: list[Point], n_sent: int) -> Point:
    """The perfect router sending at most n_sent items (it stops once no item gains)."""
    return frontier[min(n_sent, len(frontier) - 1)]


def csv_files(analyses: list[Analysis]) -> dict[str, str]:
    lead = ("first", "escalation")
    curve = [point_row(a, p, threshold=p.threshold) for a in analyses for p in a.curve]
    frontier = [point_row(a, p, optimised_for=m) for a in analyses for m, ps in a.frontiers.items() for p in ps]
    fixed = [
        point_row(a, p, fraction=f, perfect_router_mean_of_4=best_at(a.frontiers[MEAN], p.n_sent).accuracy[MEAN].value)
        for a in analyses
        for f, p in a.fixed.items()
    ]
    splits = [
        {
            "first": a.pair.first_ref.model,
            "escalation": a.pair.escalate_ref.model,
            "decision_questions": " ".join(r.decision_questions),
            "headline": r.headline,
            "n": a.curve[0].n,
            "cost_per_1000_usd": r.cost_per_1000,
            "latency_p50_s": r.latency_p50,
            **acc_columns(r.accuracy),
            **({f"diff_vs_llm_{k}": getattr(r.diff_vs_llm, k) for k in ("value", "lo", "hi")} if r.diff_vs_llm else {}),
        }
        for a in analyses
        for r in a.splits
    ]
    return {
        "cascade.csv": to_csv(curve, (*lead, "threshold")),
        "perfect_router.csv": to_csv(frontier, (*lead, "optimised_for")),
        "fixed_fractions.csv": to_csv(fixed, (*lead, "fraction")),
        "splits.csv": to_csv(splits, (*lead, "decision_questions", "headline")),
    }


def fmt(a: Accuracy) -> str:
    return f"{a.value:.{DIGITS}f} [{a.lo:.{DIGITS}f}, {a.hi:.{DIGITS}f}]"


def money(x: float) -> str:
    return f"${x:.2f}" if x >= 0.01 or x == 0 else f"${x:.4f}"


def seconds(x: float | None) -> str:
    return "–" if x is None else f"{x:.2f}"


def row(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def point_cells(label: str, p: Point) -> list[str]:
    """A table row; '–' for a metric the point doesn't report (a perfect router reports only its own)."""
    share = f"{p.n_sent} ({p.n_sent / p.n:.0%})"
    accuracy = [fmt(p.accuracy[m]) if m in p.accuracy else "–" for m in METRICS]
    return [label, share, money(p.cost_per_1000), seconds(p.latency_p50), *accuracy]


def header(n: int, full: int) -> list[str]:
    return [f"n = {n} items." + (" " + SMOKE.format(n=n, full=full) if n < full else ""), ""]


def d_section(a: Analysis) -> list[str]:
    p = a.pair
    lines = [f"### {p.first.name} first, then {p.escalate.name}", "", *header(a.curve[0].n, p.full_n)]
    lines += [f"{p.first.name}: {p.first_note}.", ""]
    lines += [row(["Routing", "Sent to the LLM", "$ per 1,000 items", "Latency p50 (s)", *(LABEL[m] for m in METRICS)])]
    lines += [row(["---"] * (4 + len(METRICS)))]
    lines += [row(point_cells(f"{p.first.name} alone", a.curve[0]))]
    lines += [row(point_cells(f"lowest-confidence {f:.0%} sent on", pt)) for f, pt in a.fixed.items()]
    lines += [row(point_cells(f"{p.escalate.name} alone (one call)", a.llm_alone))]
    lines += [row(point_cells("perfect router, mean of 4 (bound)", a.frontiers[MEAN][-1]))]
    return [*lines, ""]


def b_section(a: Analysis) -> list[str]:
    p = a.pair
    lines = [f"### {p.first.name} + {p.escalate.name}", "", *header(a.curve[0].n, p.full_n)]
    lines += [row(["Decision model answers", "LLM answers", "$ per 1,000 items", *(LABEL[m] for m in METRICS)])]
    lines += [row(["---"] * (3 + len(METRICS)))]
    for r in a.splits:
        mine = ", ".join(SHORT[q] for q in r.decision_questions) or "none"
        theirs = ", ".join(SHORT[q] for q in QUESTIONS if q not in r.decision_questions) or "none"
        label = f"**{mine}** (pre-registered)" if r.headline else mine
        lines.append(row([label, theirs, money(r.cost_per_1000), *(fmt(r.accuracy[m]) for m in METRICS)]))
    head = next(r for r in a.splits if r.headline)
    if head.diff_vs_llm:
        d = head.diff_vs_llm
        lines += [
            "",
            f"Pre-registered split minus {p.escalate.name} alone, mean of 4 (paired bootstrap): "
            f"{d.value:+.{DIGITS}f} [{d.lo:+.{DIGITS}f}, {d.hi:+.{DIGITS}f}].",
        ]
    return [*lines, ""]


def tables_md(analyses: list[Analysis], cfg_path: Path, prices: PriceTable) -> str:
    lines = [
        GENERATED,
        "",
        "# Part 2 designs D and B (text benchmark)",
        "",
        f'From saved replies only (`{cfg_path.name}`); choices in WORKLOG 2026-10-13, "Part 2 design analysis". Numbers only.',
        "",
        "- Accuracy: the exact answer per question (Q2 and Q4: exact severity level, as in Fig 4). Mean of 4 = each item's "
        "share of its 4 questions right, averaged over items. 95% CIs: Wilson for one question, bootstrap over items for "
        "the mean of 4. An unanswered question is wrong.",
        f"- $: logged tokens x `configs/prices.yaml` (checked {prices.checked.isoformat()}), per 1,000 items. Latency: the "
        "median over items of the item's calls added up (a routed item waits for both).",
        "- D: an item's confidence is its lowest top-option probability over the 4 questions. At a fixed share, the "
        "lowest-confidence items go to the LLM (ties by item id), which answers all 4 questions for them. The perfect router "
        "sends only the items where the LLM gets more right: a bound, not a system.",
        "- B: one LLM call answers all 4 questions, so any split that uses the LLM costs both calls.",
        "",
        "## D: route by confidence",
        "",
    ]
    for a in analyses:
        lines += d_section(a)
    lines += ["## B: split by question", ""]
    for a in analyses:
        lines += b_section(a)
    return "\n".join(lines).rstrip() + "\n"


def draw(a: Analysis, claims: Claims, path: Path) -> None:
    """One figure per pair: mean of 4 and each question, accuracy against $ per 1,000 items."""
    p = a.pair
    fig, axes = plt.subplots(2, 3, figsize=(13, 7.5), sharex=True)
    shade = color(p.first.name)
    for ax, m in zip(axes.flat, METRICS, strict=False):
        xs = [pt.cost_per_1000 for pt in a.curve]
        ax.fill_between(
            xs, [pt.accuracy[m].lo for pt in a.curve], [pt.accuracy[m].hi for pt in a.curve], color=shade, alpha=0.15, lw=0
        )
        ax.plot(xs, [pt.accuracy[m].value for pt in a.curve], color=shade, lw=1.6, label="route by confidence (95% CI band)")
        bound = a.frontiers[m]
        ax.plot(
            [b.cost_per_1000 for b in bound], [b.accuracy[m].value for b in bound], "k--", lw=1, label="perfect router (bound)"
        )
        for pt, mark, label in [(a.curve[0], "o", f"{p.first.name} alone"), (a.llm_alone, "s", f"{p.escalate.name} alone")]:
            acc = pt.accuracy[m]
            yerr = [[max(0.0, acc.value - acc.lo)], [max(0.0, acc.hi - acc.value)]]  # bootstrap rounding at 0 or 1
            ax.errorbar(pt.cost_per_1000, acc.value, yerr=yerr, fmt=mark, color="k", ms=6, capsize=3, label=label)
        for f, pt in a.fixed.items():
            ax.plot(pt.cost_per_1000, pt.accuracy[m].value, "D", color=shade, ms=5, mec="k", mew=0.6)
            ax.annotate(
                f"{f:.0%}", (pt.cost_per_1000, pt.accuracy[m].value), textcoords="offset points", xytext=(4, -10), fontsize=7
            )
        base = baseline(claims, f"{m}_accuracy") if m != MEAN else None
        if base is not None:
            ax.axhline(base, color="0.5", ls=":", lw=1, label="majority answer")
        ax.set_title(LABEL[m], fontsize=10)
        ax.set_ylim(0, 1)
        ax.grid(alpha=0.3)
    for ax in axes[-1]:
        ax.set_xlabel("$ per 1,000 items")
    for ax in axes[:, 0]:
        ax.set_ylabel("accuracy")
    legend_ax = axes.flat[-1]
    legend_ax.axis("off")
    handles, labels = axes.flat[METRICS.index(QUESTIONS[1])].get_legend_handles_labels()  # a panel with a majority line
    legend_ax.legend(handles, labels, loc="upper left", fontsize=8, frameon=False)
    n = a.curve[0].n
    note = f"n = {n}" + (f" (smoke run: fewer than {p.full_n})" if n < p.full_n else "")
    text = "\n".join([note, "◆ lowest-confidence share sent on", textwrap.fill(f"{p.first.name}: {p.first_note}", NOTE_WIDTH)])
    legend_ax.text(0, 0.35, text, fontsize=8, va="top")
    fig.suptitle(f"{p.first.name} first; low-confidence items to {p.escalate.name}", fontsize=12)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    for ext in FIG_FORMATS:
        fig.savefig(path.with_suffix(f".{ext}"), dpi=150, metadata={"CreationDate": None} if ext == "pdf" else None)
    plt.close(fig)


def pairs(cfg: DesignConfig, runs: list[RunData], prices: PriceTable) -> list[Pair]:
    out = []
    for esc in cfg.escalation:
        llm = system(runs, esc, prices, None)
        for ref in cfg.first:
            first = system(runs, ref, prices, cfg.confidence)
            out.append(Pair(first, llm, ref, esc, price_note(prices, ref.model), len(llm.items)))
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", type=Path, default=CONFIG_PATH)
    ap.add_argument("--results", type=Path, default=ROOT / "results")
    ap.add_argument("--figures", type=Path, default=ROOT / "figures")
    ap.add_argument("--prices", type=Path, default=PRICES_PATH)
    ap.add_argument("--claims", type=Path, default=CLAIMS_PATH)
    ap.add_argument("--check", action="store_true", help="compare the tables with a fresh rebuild instead of writing")
    args = ap.parse_args(argv)

    cfg = DesignConfig.model_validate(yaml.safe_load(args.config.read_text()))
    prices = load_prices(args.prices)
    analyses = [analyse(p, cfg) for p in pairs(cfg, load_results(args.results), prices)]
    files = csv_files(analyses) | {"tables.md": tables_md(analyses, args.config, prices)}
    out = args.results / args.config.stem
    if args.check:
        stale = [name for name, text in files.items() if not (out / name).exists() or (out / name).read_text() != text]
        for name in stale:
            print(f"stale: {out / name}")
        return 1 if stale else 0
    out.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (out / name).write_text(text)
    claims = load_claims(args.claims)
    for a in analyses:
        draw(a, claims, args.figures / args.config.stem / f"cascade_{a.pair.first_ref.model}_to_{a.pair.escalate_ref.model}")
    print(f"wrote {len(files)} tables to {out} and {len(analyses)} figures to {args.figures / args.config.stem}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
