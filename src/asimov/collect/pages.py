"""Markdown pages under results/: pure functions from loaded runs to text. Numbers only, no
interpretation (CLAUDE.md). No prompt or scenario text: that's dataset content we don't commit.
"""

from __future__ import annotations

from dataclasses import dataclass

from asimov.bench.text_score import QUESTIONS
from asimov.claims import Claims, Headline, is_stand_in, paper_value
from asimov.collect.checks import (
    ACTION_QUESTIONS,
    LATENT_QUESTIONS,
    CheckRow,
    actions_harder,
    close_to_paper,
    paper_check,
    size_gap,
)
from asimov.collect.load import ModelResult, RunData
from asimov.collect.metrics import DENOMINATORS, Estimate, correct_by_question, estimate, item_rows, paired
from asimov.collect.run_ids import RunLabel, description

GENERATED = "<!-- Generated by scripts/collect.py from results/. Don't edit by hand: rerun it. -->"
EXCERPT_CHARS = 160
MAX_DISAGREEMENTS = 50  # per model on a comparison page
DATE_CHARS = 10  # "YYYY-MM-DD" at the start of scored_at
RUN_PAGE_COMMIT_CHARS = 10  # git commit shown on a run page
SUMMARY_COMMIT_CHARS = 7  # git commit shown in the summary's "All runs" table
CONFIG_SHA_CHARS = 12  # config.yaml sha256 shown on a run page
P_DIGITS = 4  # decimals for McNemar and Holm p-values
# figure -> (benchmark, metrics in its table, figure files); fig6 waits for the image scorer
FIGURES = {
    "fig4": ("text", tuple(f"{q}_accuracy" for q in QUESTIONS), ("fig4a", "fig4b")),
    "fig5": ("video", ("risk_accuracy", "timing_mae_s", "within_0_5_rate"), ("fig5a", "fig5b")),
    "fig6": ("image", ("violation_rate",), ("fig6a",)),
}


def num(v: float | None, digits: int = 3) -> str:
    return "–" if v is None else f"{v:.{digits}f}"


def with_ci(e: Estimate | None) -> str:
    if e is None:
        return "–"
    return num(e.value) if e.lo is None else f"{num(e.value)} [{num(e.lo)}, {num(e.hi)}]"


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def cell_text(text: str) -> str:
    """Free text (an owner's description) safe inside a Markdown table cell."""
    return " ".join(text.split()).replace("|", "\\|")


def excerpt(text: str) -> str:
    one_line = " ".join(text.split())
    short = one_line[:EXCERPT_CHARS] + ("…" if len(one_line) > EXCERPT_CHARS else "")
    return short.replace("|", "\\|").replace("<", "&lt;")


def scored_date(run: RunData) -> str:
    return max((m.summary.get("scored_at") or "")[:DATE_CHARS] for m in run.models)


# ---- run page -------------------------------------------------------------------------------


def settings_section(run: RunData) -> str:
    s = [m.summary for m in run.models]
    commits = sorted(
        {(x.get("git_commit") or "")[:RUN_PAGE_COMMIT_CHARS] + (" (dirty)" if x.get("git_dirty") else "") for x in s}
    )
    configs = sorted({(x.get("config_sha256") or "")[:CONFIG_SHA_CHARS] for x in s})
    rows = [
        ["Benchmark", run.benchmark],
        ["Prompt", ", ".join(sorted({str(x.get("prompt")) for x in s}))],
        ["Thinking", ", ".join(sorted({str(x.get("thinking")) for x in s}))],
        ["Reasoning logged", ", ".join(sorted({str(x.get("log_reasoning", False)) for x in s}))],
        ["Git commit", ", ".join(commits)],
        ["Scored", scored_date(run)],
        ["Config", f"[config.yaml](config.yaml) (sha256 {', '.join(configs)})" if run.config else "–"],
    ]
    return "## Settings\n\n" + table(["Setting", "Value"], rows)


def near_key_reads(m: ModelResult) -> int:
    return sum(v == "near_key" for o in m.per_item.values() for v in (o.get("parse") or {}).values())


def count(rate: float | None, n: int) -> int:
    return round((rate or 0.0) * n)


@dataclass(frozen=True)
class FailureCounts:
    failed: int  # parse failures: no answer could be read
    refused: int
    truncated: int
    malformed: int | None  # None when per_item can't tell (no parse_ok)


def failure_counts(m: ModelResult) -> FailureCounts:
    """Parse failures split by how the reply ended (`finish`).

    With per-item `parse_ok` (text): counted per item, so the parts add up and a truncated reply
    whose answer was still readable isn't a failure. Without it (video): the summary's rates x n,
    and malformed is unknown.
    """
    items = list(m.per_item.values())
    if items and all("parse_ok" in o for o in items):
        failed = [o for o in items if not o["parse_ok"]]
        by_finish = {f: sum(o.get("finish") == f for o in failed) for f in ("refused", "truncated", "complete")}
        return FailureCounts(len(failed), by_finish["refused"], by_finish["truncated"], by_finish["complete"])
    s, n = m.summary, m.summary.get("n", 0)
    failed, refused, truncated = (count(s.get(k), n) for k in ("parse_failure_rate", "refusal_rate", "truncation_rate"))
    return FailureCounts(failed, refused, truncated, None)


def model_row(m: ModelResult, index_row: dict) -> list[str]:
    s, n = m.summary, m.summary.get("n", 0)
    fails = failure_counts(m)
    p50, p95 = index_row.get("latency_p50_s"), index_row.get("latency_p95_s")
    return [
        m.name,
        f"`{s['model']}`",
        ", ".join(f"`{x}`" for x in m.served_models) or "–",
        "yes" if is_stand_in(m.name) else "",
        str(n),
        str(s.get("errors", 0)),
        str(fails.failed),
        str(fails.refused),
        str(fails.truncated),
        "–" if fails.malformed is None else str(fails.malformed),
        str(near_key_reads(m)),
        str(s.get("n_with_reasoning", "–")),
        str(s.get("input_tokens", "–")),
        str(s.get("output_tokens", "–")),
        num(index_row.get("cost_usd"), 2),
        f"{num(p50, 1)} / {num(p95, 1)}",
    ]


def models_section(run: RunData, index: dict[tuple[str, str], dict]) -> str:
    header = [
        "Model",
        "Requested",
        "Served",
        "Stand-in",
        "Replies",
        "Errors",
        "Parse failures",
        "Refused",
        "Truncated",
        "Malformed",
        "Near-key reads",
        "With reasoning",
        "Input tokens",
        "Output tokens",
        "Cost $",
        "Latency p50 / p95 s",
    ]
    rows = [model_row(m, index[run.name, m.summary["model"]]) for m in run.models]
    note = (
        "Parse failures: replies with no readable answer; all count as wrong (CLAUDE.md, scoring conventions). "
        "With per-item `parse_ok` in `summary.json` (text), Refused, Truncated and Malformed split the parse failures "
        "by how the reply ended (`finish` = refused, truncated, complete), so they add up; a truncated reply whose "
        "answer was still read is not a parse failure. Without it (video), Parse failures, Refused and Truncated are "
        "the summary's rates × replies (Refused and Truncated then count every refused or cut-off reply) and "
        'Malformed is "–". Cost is "–" until `configs/prices.yaml` has the model.'
    )
    return "## Models\n\n" + table(header, rows) + "\n\n" + note


def metrics_section(run: RunData) -> str:
    metrics = list(DENOMINATORS.get(run.benchmark, {}))
    rows = [[m.name] + [with_ci(estimate(m, run.benchmark, k)) for k in metrics] for m in run.models]
    return (
        "## Metrics (95% CI)\n\n"
        + table(["Model", *metrics], rows)
        + ("\n\nCIs: Wilson for rates, bootstrap over items for means (`src/asimov/stats.py`).")
    )


def files_section(run: RunData) -> str:
    rows = [
        [m.name, f"[responses.jsonl]({m.summary['model']}/responses.jsonl)", f"[summary.json]({m.summary['model']}/summary.json)"]
        for m in run.models
    ]
    return (
        "## Files\n\n"
        + table(["Model", "Replies", "Summary"], rows)
        + ("\n\nScoring decisions behind these numbers: [WORKLOG.md](../../WORKLOG.md).")
    )


def run_page(run: RunData, index: dict[tuple[str, str], dict], has_claims: bool, labels: dict[str, RunLabel]) -> str:
    parts = [
        GENERATED,
        f"# Run `{labels[run.name].id}`: `{run.name}`",
        description(run, labels),
        settings_section(run),
        models_section(run, index),
        metrics_section(run),
        files_section(run),
    ]
    if has_claims:
        parts.append(
            "## Paper check\n\nOurs vs every number the paper reports for this benchmark: [paper_check.md](paper_check.md)."
        )
    return "\n\n".join(parts) + "\n"


# ---- paper check ----------------------------------------------------------------------------


def check_rows_table(rows: list[CheckRow]) -> str:
    header = [
        "Claim",
        "Fig / §",
        "Kind",
        "Model (paper)",
        "Ours",
        "Metric",
        "Paper",
        "Ours [95% CI]",
        "Diff",
        "Paper in CI",
        "Stand-in",
        "Status",
    ]
    body = [
        [
            f"`{r.claim.id}`",
            f"{r.claim.figure or '–'} / {r.claim.section}",
            r.claim.kind,
            r.claim.model or ", ".join(r.claim.models) or "–",
            ", ".join(r.our_models) or "–",
            r.claim.metric,
            num(r.paper) + ("~" if r.claim.approx else ""),
            with_ci(r.ours),
            num(r.diff),
            {True: "yes", False: "no", None: "–"}[r.paper_in_ci],
            "yes" if r.stand_in else "",
            r.status,
        ]
        for r in rows
    ]
    return table(header, body)


def close_to_paper_section(run: RunData, h: Headline, rows: list[CheckRow]) -> str:
    return table(
        ["Model", "Paper values checked", "Paper value inside our CI", "Mean abs(ours − paper)"],
        [[r.model, str(r.n_checked), str(r.n_inside), num(r.mean_abs_diff)] for r in close_to_paper(rows, h)],
    )


def size_gap_section(run: RunData, h: Headline, rows: list[CheckRow]) -> str:
    return table(
        ["Pair", "Question", "Items", "Large − small [95% CI]", "McNemar p", "Holm p"],
        [
            [
                f"{g.large} minus {g.small}",
                g.question,
                str(g.result.n),
                f"{num(g.result.diff)} [{num(g.result.lo)}, {num(g.result.hi)}]",
                num(g.result.p, P_DIGITS),
                num(g.p_holm, P_DIGITS),
            ]
            for g in size_gap(run, h)
        ],
    )


def actions_harder_section(run: RunData, h: Headline, rows: list[CheckRow]) -> str:
    return (
        f"Per item: mean correct on {' + '.join(ACTION_QUESTIONS)} minus mean correct on "
        f"{' + '.join(LATENT_QUESTIONS)}, then averaged; paired bootstrap CI.\n\n"
        + table(
            ["Model", "Action accuracy", "Latent accuracy", "Action − latent [95% CI]"],
            [[r.model, num(r.action), num(r.latent), f"{num(r.diff)} [{num(r.lo)}, {num(r.hi)}]"] for r in actions_harder(run)],
        )
    )


HEADLINE_SECTIONS = {
    "close_to_paper": close_to_paper_section,
    "size_gap": size_gap_section,
    "actions_harder": actions_harder_section,
}


def headline_section(run: RunData, claims: Claims, rows: list[CheckRow]) -> str:
    """One subsection per headline claim: its quote, the computed check, and the note. Text runs only."""
    parts = ["## Headline claims (computed checks)"]
    for h in claims.headline:
        parts.append(f"### `{h.id}` ({h.check}, §{h.section})\n\n> {h.quote}")
        parts.append(HEADLINE_SECTIONS[h.check](run, h, rows))
        if h.note:
            parts.append(f"Note: {h.note}")
    return "\n\n".join(parts)


def paper_check_page(run: RunData, claims: Claims) -> str:
    rows = paper_check(run, claims)
    p = claims.paper
    intro = (
        f"Paper: arXiv {p.arxiv}{p.version}, read on {p.read_on} into `configs/paper/claims.yaml`. "
        "Values are on our scale (fractions, seconds); `~` marks a value read off a figure. "
        '"Paper in CI" is only computed for single-model values. Stand-in rows compare our model to a different paper model.'
    )
    parts = [GENERATED, f"# Paper check: `{run.name}`", intro, check_rows_table(rows)]
    if run.benchmark == "text" and claims.headline:
        parts.append(headline_section(run, claims, rows))
    return "\n\n".join(parts) + "\n"


def check_csv_rows(run: RunData, claims: Claims) -> list[dict]:
    return [
        {
            "claim": r.claim.id,
            "figure": r.claim.figure,
            "kind": r.claim.kind,
            "model_paper": r.claim.model,
            "models_ours": ";".join(r.our_models),
            "metric": r.claim.metric,
            "paper": r.paper,
            "approx": r.claim.approx,
            "ours": None if r.ours is None else r.ours.value,
            "ci_lo": None if r.ours is None else r.ours.lo,
            "ci_hi": None if r.ours is None else r.ours.hi,
            "diff": r.diff,
            "paper_in_ci": r.paper_in_ci,
            "stand_in": r.stand_in,
            "status": r.status,
        }
        for r in paper_check(run, claims)
    ]


# ---- summary page ---------------------------------------------------------------------------


def figure_section(fig: str, run: RunData | None, note: str, claims: Claims, labels: dict[str, RunLabel]) -> str:
    benchmark, metrics, files = FIGURES[fig]
    title = f"## Fig {fig[3:]} ({benchmark})"
    if run is None:
        return f"{title}\n\nNo run yet." + (f" {note}" if note else "")
    header = ["Model"] + [h for k in metrics for h in (k, "paper")]
    rows = [
        [m.name]
        + [x for k in metrics for x in (with_ci(estimate(m, benchmark, k)), num(paper_value(claims, benchmark, m.name, k)))]
        for m in run.models
    ]
    images = " ".join(f"![{f}](../figures/{f}_comparison.png)" for f in files)
    run_line = f"Run: `{labels[run.name].id}` [`{run.name}`]({run.name}/README.md) · [paper check]({run.name}/paper_check.md)"
    lines = [title, run_line]
    if note:
        lines.append(f"Note ({run.name} owner): {note}")
    return "\n\n".join([*lines, table(header, rows), images])


def all_runs_section(runs: list[RunData], index: dict[tuple[str, str], dict], notes: dict, labels: dict[str, RunLabel]) -> str:
    def cost(run: RunData) -> str:
        costs = [index[run.name, m.summary["model"]].get("cost_usd") for m in run.models]
        return num(sum(c for c in costs if c is not None), 2) if any(c is not None for c in costs) else "–"

    ordered = sorted(runs, key=lambda r: (scored_date(r), r.name), reverse=True)
    rows = [
        [
            f"`{labels[r.name].id}`",
            f"[`{r.name}`]({r.name}/README.md)",
            cell_text(description(r, labels)),
            r.benchmark,
            scored_date(r),
            str(len(r.models)),
            ", ".join(sorted({str(m.summary.get("thinking")) for m in r.models})),
            ", ".join(sorted({str(m.summary.get("prompt")) for m in r.models})),
            ", ".join(sorted({(m.summary.get("git_commit") or "")[:SUMMARY_COMMIT_CHARS] for m in r.models})),
            cost(r),
            notes.get(r.name) or "",
        ]
        for r in ordered
    ]
    return "## All runs\n\n" + table(
        ["Run ID", "Run", "Description", "Benchmark", "Date", "Models", "Thinking", "Prompt", "Commit", "Cost $", "Note"], rows
    )


def summary_page(
    runs: list[RunData], index: dict[tuple[str, str], dict], headline: dict, claims: Claims, labels: dict[str, RunLabel]
) -> str:
    by_name = {r.name: r for r in runs}
    figures = headline.get("figures") or {}
    intro = (
        "Headline numbers per figure, from the run chosen in [`headline.yaml`](headline.yaml) (hand-edited). "
        "95% CIs in brackets; `paper` is the paper's value for the same model (`configs/paper/claims.yaml`). "
        "Tables: [`index.csv`](index.csv), [`per_item.csv`](per_item.csv)."
    )
    sections = [
        figure_section(
            fig,
            by_name.get((figures.get(fig) or {}).get("run") or ""),
            (figures.get(fig) or {}).get("note") or "",
            claims,
            labels,
        )
        for fig in FIGURES
    ]
    return (
        "\n\n".join([GENERATED, "# Results", intro, *sections, all_runs_section(runs, index, headline.get("runs") or {}, labels)])
        + "\n"
    )


# ---- comparison page ------------------------------------------------------------------------


def disagreements(a: ModelResult, b: ModelResult, benchmark: str) -> str:
    rows = []
    by_a, by_b = correct_by_question(a, benchmark), correct_by_question(b, benchmark)
    for item_id in sorted(a.per_item.keys() & b.per_item.keys()):
        ra = {r["question"]: r for r in item_rows(benchmark, a.per_item[item_id])}
        rb = {r["question"]: r for r in item_rows(benchmark, b.per_item[item_id])}
        for q in by_a:
            if q in rb and by_a[q].get(item_id) != by_b.get(q, {}).get(item_id):
                rows.append(
                    [
                        item_id,
                        q,
                        str(ra[q]["gold"]),
                        str(ra[q]["pred"]),
                        str(rb[q]["pred"]),
                        excerpt(a.replies.get(item_id, "")),
                        excerpt(b.replies.get(item_id, "")),
                    ]
                )
    shown = rows[:MAX_DISAGREEMENTS]
    more = f"\n\n({len(rows) - len(shown)} more not shown.)" if len(rows) > len(shown) else ""
    return table(["Item", "Question", "Gold", "A", "B", "A reply (start)", "B reply (start)"], shown) + more


def comparison_page(name: str, a: RunData, b: RunData, note: str, labels: dict[str, RunLabel]) -> str:
    link_a, link_b = (f"`{labels[r.name].id}` [`{r.name}`](../{r.name}/README.md)" for r in (a, b))
    parts = [
        GENERATED,
        f"# Comparison `{name}`: {link_a} (A) vs {link_b} (B)",
        f"- A: {description(a, labels)}\n- B: {description(b, labels)}",
    ]
    if note:
        parts.append(note)
    if a.benchmark != b.benchmark:
        return "\n\n".join([*parts, f"Not comparable: benchmarks differ ({a.benchmark} vs {b.benchmark})."]) + "\n"
    b_models = {m.summary["model"]: m for m in b.models}
    for ma in a.models:
        mb = b_models.get(ma.summary["model"])
        if mb is None:
            continue
        qa, qb = correct_by_question(ma, a.benchmark), correct_by_question(mb, b.benchmark)
        rows = []
        for q in qa:
            p = paired(qa[q], qb.get(q, {}))
            if p:
                rows.append(
                    [q, str(p.n), f"{num(p.diff)} [{num(p.lo)}, {num(p.hi)}]", str(p.a_only), str(p.b_only), num(p.p, P_DIGITS)]
                )
        parts.append(
            f"## {ma.name}\n\n"
            + table(["Question", "Items", "A − B accuracy [95% CI]", "A right only", "B right only", "McNemar p"], rows)
        )
        parts.append(
            f"<details><summary>Items where A and B differ</summary>\n\n{disagreements(ma, mb, a.benchmark)}\n\n</details>"
        )
    return "\n\n".join(parts) + "\n"
