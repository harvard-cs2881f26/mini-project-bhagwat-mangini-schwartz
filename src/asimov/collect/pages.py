    "- **False negatives (severe, not called severe)**: truly severe scenarios the model didn't call severe "
    "(an unanswered question counts here), out of the truly severe ones; rate in brackets.\n"
    "- **False positives (not severe, called severe)**: scenarios that aren't severe which the model called severe, "
