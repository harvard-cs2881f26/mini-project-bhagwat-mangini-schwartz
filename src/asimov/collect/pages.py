def disagreements(a: ModelResult, b: ModelResult, benchmark: str) -> str:
    rows = []
    by_a, by_b = correct_by_question(a, benchmark), correct_by_question(b, benchmark)
    for item_id in sorted(a.per_item.keys() & b.per_item.keys()):
        ra = {r["question"]: r for r in item_rows(benchmark, a.per_item[item_id])}
        rb = {r["question"]: r for r in item_rows(benchmark, b.per_item[item_id])}
        for q in by_a:
            if q in rb and by_a[q].get(item_id) != by_b.get(q, {}).get(item_id):
                rows.append(
                    [
                        item_id,
                        q,
                        str(ra[q]["gold"]),
                        str(ra[q]["pred"]),
                        str(rb[q]["pred"]),
                        excerpt(a.replies.get(item_id, "")),
                        excerpt(b.replies.get(item_id, "")),
                    ]
                )
    shown = rows[:MAX_DISAGREEMENTS]
    more = f"\n\n({len(rows) - len(shown)} more not shown.)" if len(rows) > len(shown) else ""
    return table(["Item", "Question", "Gold", "A", "B", "A reply (start)", "B reply (start)"], shown) + more


def comparison_page(name: str, a: RunData, b: RunData, note: str, labels: dict[str, RunLabel]) -> str:
    link_a, link_b = (f"`{labels[r.name].id}` [`{r.name}`](../{r.folder}/README.md)" for r in (a, b))
    parts = [
        GENERATED,
        f"# Comparison `{name}`: {link_a} (A) vs {link_b} (B)",
        f"- A: {labels[a.name].description}\n- B: {labels[b.name].description}",
    ]
    if note:
        parts.append(note)
    if a.benchmark != b.benchmark:
        return "\n\n".join([*parts, f"Not comparable: benchmarks differ ({a.benchmark} vs {b.benchmark})."]) + "\n"
    b_models = {m.summary["model"]: m for m in b.models}
    for ma in a.models:
        mb = b_models.get(ma.summary["model"])
        if mb is None:
            continue
        qa, qb = correct_by_question(ma, a.benchmark), correct_by_question(mb, b.benchmark)
        rows = []
        for q in qa:
            p = paired(qa[q], qb.get(q, {}))
            if p:
                rows.append(
                    [q, str(p.n), f"{num(p.diff)} [{num(p.lo)}, {num(p.hi)}]", str(p.a_only), str(p.b_only), num(p.p, P_DIGITS)]
                )
        parts.append(
            f"## {ma.name}\n\n"
            + table(["Question", "Items", "A − B accuracy [95% CI]", "A right only", "B right only", "McNemar p"], rows)
        )
        parts.append(
            f"<details><summary>Items where A and B differ</summary>\n\n{disagreements(ma, mb, a.benchmark)}\n\n</details>"
        )
    return "\n\n".join(parts) + "\n"
