def extras_part(run: RunData, runs: list[RunData], labels: dict[str, RunLabel], claims: Claims) -> str | None:
    """The "Across models" subsection: each extra chart with its note and key insight."""
    run_id = labels[run.name].id
    blocks = []
    for stem, kind, twin in extra_figures(run, runs, {n: lab.id for n, lab in labels.items()}):
        note = EXTRA_NOTES[kind] + ("" if twin is None else " " + twin_line(run, twin, labels))
        image = f"![{stem}](../../{extra_figure_file(run_id, stem)})"
        blocks.append(f"{note}\n\n{with_insight(image, extra_insight(kind, run, claims, twin))}")
    return "\n\n".join([f"### {EXTRA_SUBHEADING}", *blocks]) if blocks else None


def figures_section(run: RunData, runs: list[RunData], headline: dict, labels: dict[str, RunLabel], claims: Claims) -> str:
    names = run_figures(run, runs, headline)
    if not names:
        return "## Figures\n\nNo figures for this benchmark yet (`scripts/plot.py` draws Figs 4 and 5)."
    run_id = labels[run.name].id
    intro = (
        f"Drawn by `scripts/plot.py` into `{FIGURES_DIR}/{run_id}/` (PNG and PDF). Comparison: ours with 95% CIs, "
        "the paper's values and majority baselines; paper-style: the paper's look, our values only."
    )
    partner = fig5a_partner(run, runs, headline)
    if partner is not None:
        intro += (
            f" Fig 5a pairs this run with the headline {partner.benchmark} run `{labels[partner.name].id}` "
            f"[`{partner.name}`](../{partner.folder}/README.md) ([`headline.yaml`](../headline.yaml))."
        )
    parts = ["## Figures", intro]
    for version in FIGURE_VERSIONS:  # paper-style versions show the same data as the comparison ones: no insight
        images = [
            with_insight(
                f"![{f}, {version}](../../{figure_file(run_id, f, version)})",
                comparison_insight(f, run, partner, claims) if version == "comparison" else None,
            )
            for f in names
        ]
        parts.append("\n\n".join([f"### {FIGURE_SUBHEADINGS[version]}", FIGURE_VERSION_NOTES[version], *images]))
    extras = extras_part(run, runs, labels, claims)
    if extras is not None:
        parts.append(extras)
    return "\n\n".join(parts)


def has_paper_check(run: RunData, claims: Claims) -> bool:
    """Whether the run gets a paper_check.md and table.csv: the paper reports numbers for its benchmark."""
    return any(c.benchmark == run.benchmark for c in claims.claims)


def paper_section(run: RunData, claims: Claims) -> str:
    if not has_paper_check(run, claims):
        return "## Comparison with the paper\n\nNo paper numbers for this benchmark in `configs/paper/claims.yaml`."
    parts = paper_check_parts(run, claims, level=3)
    parts[0] += " The same, as its own page: [paper_check.md](paper_check.md)."
    return "\n\n".join(["## Comparison with the paper", *parts])


def out_of(hits: int | None, total: int | None) -> str:
    return "–" if hits is None or total is None else f"{hits} / {total}"


def severity_cells(r: SeverityRow) -> list[str]:
    caught = "–" if r.caught is None else num(r.caught)
    if r.caught is not None and r.n_severe is not None:
        caught += f" ({out_of(count(r.caught, r.n_severe), r.n_severe)})"
    return [
        r.model,
        num(r.exact),
        num(r.severe_vs_not),
        caught,
        "–" if r.false_negatives is None else f"{out_of(r.false_negatives, r.n_severe)} ({num(r.false_negative_rate)})",
        "–" if r.false_positives is None else f"{out_of(r.false_positives, r.n_not_severe)} ({num(r.false_positive_rate)})",
    ]


