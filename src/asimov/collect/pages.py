def num(v: float | None, digits: int = 3) -> str:
    return "–" if v is None else f"{v:.{digits}f}"


def with_ci(e: Estimate | None) -> str:
    if e is None:
        return "–"
    return num(e.value) if e.lo is None else f"{num(e.value)} [{num(e.lo)}, {num(e.hi)}]"


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def cell_text(text: str) -> str:
    """Free text (a run description) safe inside a Markdown table cell."""
    return " ".join(text.split()).replace("|", "\\|")


def excerpt(text: str) -> str:
    one_line = " ".join(text.split())
    short = one_line[:EXCERPT_CHARS] + ("…" if len(one_line) > EXCERPT_CHARS else "")
    return short.replace("|", "\\|").replace("<", "&lt;")


def scored_date(run: RunData) -> str:
    return max((m.summary.get("scored_at") or "")[:DATE_CHARS] for m in run.models)


