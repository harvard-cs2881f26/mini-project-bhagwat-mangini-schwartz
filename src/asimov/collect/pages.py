def paper_gap_line(run: RunData, claims: Claims, question: str) -> str:
    gaps, n_models = paper_gaps(run, claims, question)
    values = " · ".join(f"{scoring} {num(gap)}" for scoring, gap in gaps.items())
    return (
        "How close each scoring comes to the paper's Fig 4a severity values "
        f"(mean absolute gap over models with a paper value): {values} ({n_models} models)."
    )


def severity_section(run: RunData, claims: Claims) -> str:
    """Text runs: each severity question scored several ways, per model, plus Q2's gap to the paper."""
    parts = ["## Ways to score severity", SEVERITY_INTRO]
    for q in SEVERITY_QUESTIONS:
        parts.append(f"### {SEVERITY_TITLES[q]}")
        parts.append(table(SEVERITY_HEADER, [severity_cells(severity_row(m, q)) for m in run.models]))
        if q == "latent_severity":
            parts.append(paper_gap_line(run, claims, q))
    return "\n\n".join(parts)


def files_section(run: RunData) -> str:
    rows = [
        [m.name, f"[responses.jsonl]({m.summary['model']}/responses.jsonl)", f"[summary.json]({m.summary['model']}/summary.json)"]
        for m in run.models
    ]
    return (
        "## Files\n\n"
        + table(["Model", "Replies", "Summary"], rows)
        + ("\n\nScoring decisions behind these numbers: [WORKLOG.md](../../WORKLOG.md).")
    )


def run_page(
    run: RunData,
    index: dict[tuple[str, str], dict],
    claims: Claims,
    labels: dict[str, RunLabel],
    runs: list[RunData],
    headline: dict,
) -> str:
    """The run's report: write-up, figures, ours vs the paper, cost and speed, then settings, models, metrics and files."""
    parts = [
        GENERATED,
        f"# Run `{labels[run.name].id}`: `{run.name}`",
        labels[run.name].description,
        writeup_section(run),
        figures_section(run, runs, headline, labels, claims),
        paper_section(run, claims),
        cost_section(run, index),
        settings_section(run),
        models_section(run, index),
        metrics_section(run),
        *([severity_section(run, claims)] if run.benchmark == "text" else []),
        files_section(run),
    ]
    return "\n\n".join(parts) + "\n"


